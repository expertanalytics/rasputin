"""30c acceptance tables, generated from raw/: timing medians, the gate, byte-identity, power, quality.

Modelled on 30b's (`../../30b-clip/scripts/summarize.py`). Writes raw/summary.md
and replaces the region between the GENERATED markers in README.md with it, so
the README's figures come from the raw files only.
"""

import re
import statistics
from pathlib import Path

HERE = Path(__file__).resolve().parent.parent
R = HERE / "raw" / "stats"
RAW = HERE / "raw"
CATCH = {"numedalslagen": "Numedalslågen", "skiensvassdraget": "Skiensvassdraget"}
SIDES = ("base", "branch")
REPS = (1, 2, 3)
GATED = "decode"
GATE = 0.7
ROW = re.compile(r"^\| \**([a-z :+()]+?)\** \| \**([0-9.]+)\**")
START, END = "<!-- GENERATED by scripts/summarize.py: do not edit by hand -->", "<!-- END GENERATED -->"


def timings(path: Path) -> dict[str, str]:
    text = path.read_text()
    out: dict[str, str] = {}
    for line in text[text.index("## Timings"):].splitlines():
        m = ROW.match(line)
        if m:
            out.setdefault(m.group(1), m.group(2))
    return out


def stats(side: str, c: str, r: int) -> dict[str, str]:
    path = R / f"{side}_{c}_r{r}_stats.md"
    text = path.read_text()
    out = timings(path)
    out["worst angle"] = re.search(r"^\| minimum angle \|.*\| ([0-9.e+-]+)° \|$", text, re.M).group(1)
    out["max degree"] = re.search(r"^\| vertex degree \(triangles\) \| \d+ \| \d+ \| (\d+) \|", text, re.M).group(1)
    out["max error"] = re.search(r"\| Largest height error \| ([0-9.]+) \|", text).group(1)
    out["threads"] = re.search(r"Threads: (\d+)", text).group(1)
    out["hardening"] = re.search(r"^bounds checks: (.*)$", text, re.M).group(1)
    out["seams"] = re.search(r"^\| Overlapping tiles that disagree.*?\| (.*) \| `dem_seams` \|$", text, re.M).group(1)
    return out


def power_cells(side: str, c: str, r: int) -> str:
    lines = (R / f"{side}_{c}_r{r}_power.txt").read_text().splitlines()
    cells = []
    for line in lines[:2]:
        when, rest = line.split(": ", 1)
        source = re.search(r"drawing from '([^']+)'", rest).group(1)
        pct = re.search(r"(\d+%; [a-z ]+);", rest).group(1)
        cells.append(f"{when.split(' ', 1)[1][11:]} {source}, {pct}")
    batt = lines[2].rsplit(": ", 1)[1]
    return f"| {' | '.join(cells)} | {batt} |"


def main() -> None:
    sha = dict(line.split() for line in (R / "vtk_sha256.txt").read_text().splitlines())
    power = sorted(R.glob("*_power.txt"))
    readings = [line for p in power for line in p.read_text().splitlines()[:2]]
    ac = sum("'AC Power'" in line for line in readings)
    batt_lines = sum(int(p.read_text().splitlines()[2].rsplit(": ", 1)[1]) for p in power)
    gone = sorted((RAW / "discarded").glob("*_power_*.txt")) if (RAW / "discarded").exists() else []
    busy = [g for g in gone if g.stem.endswith("_busyloop")]
    lines = [START, ""]
    lines += [f"Power: {ac} of {len(readings)} `pmset -g batt` readings (before and after each of "
              f"{len(power)} kept runs) say AC Power; `pmset -g log` holds {batt_lines} \"Using Batt\" "
              f"lines inside those runs. Runs discarded for power: {len(gone) - len(busy)}; for a busy loop of "
              f"@perf's beside the run: {len(busy)} (`raw/discarded/README.txt`).", ""]
    lines += ["### Time (median of 3, seconds)", "",
              "| catchment | phase | base `6c729e97` | branch `0663efc9` | branch / base |", "|---|---|---|---|---|"]
    per_rep, verdicts, ident, quality, rows, pw = [], [], [], [], [], []
    for c, name in CATCH.items():
        s = {(side, r): stats(side, c, r) for side in SIDES for r in REPS}
        phases = [k for k in timings(R / f"base_{c}_r1_stats.md")]
        for ph in phases:
            xs = {side: [float(s[side, r][ph]) for r in REPS] for side in SIDES}
            med = {side: statistics.median(xs[side]) for side in SIDES}
            ratio = med["branch"] / med["base"] if med["base"] else float("nan")
            rows.append(f"| {name if ph == phases[0] else ''} | {ph} | {med['base']:.3f} | {med['branch']:.3f} | "
                        f"{med['branch'] - med['base']:+.3f} |")
            if ph in (GATED, "total"):
                bold = "**" if ph == GATED else ""
                extra = f" ({med['branch'] - med['base']:+.3f} s)"
                lines.append(f"| {name if ph == GATED else ''} | {bold}{ph}{bold} | {med['base']:.3f} | "
                             f"{bold}{med['branch']:.3f}{bold} | {bold}{ratio:.3f}{bold}{extra} |")
                for side in SIDES:
                    spread = (max(xs[side]) - min(xs[side])) / med[side] * 100
                    per_rep.append(f"| {name} | {ph} | {side} | {' / '.join(f'{x:.3f}' for x in xs[side])} | {spread:.1f} % |")
            if ph == GATED:
                verdicts.append(f"| {name} | {ratio:.3f} | {'pass' if ratio <= GATE else 'FAIL'} |")
        hashes = {sha[f"{side}_{c}_r{r}"] for side in SIDES for r in REPS}
        seams = {s[side, r]["seams"] for side in SIDES for r in REPS}
        exits = {(R / f"{side}_{c}_r{r}_stderr.txt").read_text().strip().splitlines()[-1] for side in SIDES for r in REPS}
        imported = {side: {(R / f"{side}_{c}_r{r}_stderr.txt").read_text().splitlines()[0].split("/scratchpad/30c/")[1]
                           for r in REPS} for side in SIDES}
        ident.append(f"| {name} | {len(hashes)}: `{', '.join(sorted(h[:16] + '…' for h in hashes))}` | "
                     f"{len(seams)} | {', '.join(sorted(exits))} |")
        for side in SIDES:
            q = {k: sorted({s[side, r][k] for r in REPS}) for k in ("worst angle", "max degree", "max error", "threads", "hardening")}
            quality.append(f"| {name} | {side} | `{', '.join(sorted(imported[side]))}` | {', '.join(q['worst angle'])}° | "
                           f"{', '.join(q['max degree'])} | {', '.join(q['max error'])} | {', '.join(q['threads'])} | "
                           f"{', '.join(q['hardening'])} |")
            for r in REPS:
                pw.append(f"| {name} | {side} | {r} {power_cells(side, c, r)}")
    lines += ["", f"### Gate: branch `{GATED}` median at most {GATE} of the base's", "",
              "| catchment | branch / base | verdict |", "|---|---|---|", *verdicts]
    lines += ["", "### Per repeat (seconds, repeats 1 / 2 / 3; spread = (max − min) / median)", "",
              "| catchment | phase | side | values | spread |", "|---|---|---|---|---|", *per_rep]
    lines += ["", "### Every row of the `--stats` timing table (median of 3, seconds; recorded, not gated)", "",
              "| catchment | phase | base | branch | branch − base |", "|---|---|---|---|---|", *rows]
    lines += ["", "### Same output over all 6 runs per catchment", "",
              "| catchment | distinct `.vtk` sha256 | distinct `dem_seams` values | exit |", "|---|---|---|---|", *ident]
    lines += ["", "### Quality and installs (from each `--stats` and stderr file; distinct values over 3 repeats)", "",
              "| catchment | side | `tin_engine` imported (under the scratchpad) | worst angle | max vertex degree | "
              "largest height error, m | threads | bounds checks |",
              "|---|---|---|---|---|---|---|---|", *quality]
    lines += ["", "### Power, each timing run (`pmset -g batt` before and after; \"Using Batt\" lines in `pmset -g log` during the run)", "",
              "| catchment | side | repeat | before | after | battery lines |", "|---|---|---|---|---|---|", *pw]
    probe = RAW / "probe_compare.txt"
    if probe.exists():
        lines += ["", "### The byte-identical probe (`raw/probe_compare.txt`, verbatim)", "", "```", probe.read_text().rstrip(), "```"]
        pp = RAW / "probe_power.txt"
        if pp.exists():
            lines += ["", "Probe power (`raw/probe_power.txt`):", "", "```", pp.read_text().rstrip(), "```"]
    lines += ["", END]
    block = "\n".join(lines)
    (RAW / "summary.md").write_text(block + "\n")
    readme = HERE / "README.md"
    if readme.exists():
        text = readme.read_text()
        if START in text:
            text = text[: text.index(START)] + block + text[text.index(END) + len(END):]
            readme.write_text(text)
    print(block)


main()
