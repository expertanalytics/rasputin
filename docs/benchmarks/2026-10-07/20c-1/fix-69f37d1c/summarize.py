"""Tables for 20c-1's re-time after 69f37d1c, from raw files only (@perf, 2026-10-07).

``python3 summarize.py`` rewrites the block between the two marker lines in
README.md (and prints it). It reads raw/<catchment>-<variant>-r<k>.{json,power}
and raw/<...>_stats.md as run.sh writes them, bench/b1m-*/run.json from
pairs.sh, and, for the identity and gate rows only, the first acceptance's
../raw/ and ../raw1m/ (code 34b546c4). r0 is a warm-up: its mesh is in the
mesh tables, its times are not in the timing tables. Adapted from ../summarize.py.
"""

import json
import re
import statistics
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
OLD = HERE.parent
CATCH = {"tile": "1 m tile (tolerance 1)", "lagan": "Lagan", "numed": "Numedalslagen"}
VARIANTS = ["base", "head", "nofeet"]
LABEL = {"base": "master ed125121", "head": "20c-1 69f37d1c", "nofeet": "20c-1 69f37d1c, --no-constraint-feet"}
GATES = {"lagan": dict(share=0.09, worst=0.000412), "numed": dict(share=0.04, worst=0.000399)}
PHASES = ["refine", "refine: start quality", "refine: scan (parallel)", "refine: split + flip (serial)"]
SPLIT = "refine: split + flip (serial)"
BEGIN, END = "<!-- tables: generated by summarize.py -->", "<!-- end of generated tables -->"


def stat(stats: str, name: str) -> float:
    return float(re.search(r"\| ([\d.e+-]+) \| `" + name + "`", stats).group(1))


def load(dirs: list[Path]) -> dict[tuple[str, str], list[dict]]:
    runs: dict[tuple[str, str], list[dict]] = {}
    for f in sorted(p for d in dirs for p in d.glob("*-r*.json")):
        m = re.fullmatch(r"(\w+)-(\w+)-r(\d+)\.json", f.name)
        if not m:
            continue
        c, v, r = m.group(1), m.group(2), int(m.group(3))
        d = json.loads(f.read_text())
        power = (f.parent / f"{c}-{v}-r{r}.power").read_text()
        stats = (f.parent / f"{c}-{v}-r{r}_stats.md").read_text()
        d["repeat"] = r
        d["power_lines"] = [ln for ln in power.splitlines() if "InternalBattery" in ln or "drawing" in ln]
        d["proc_s"] = float(re.search(r"proc_s: (\S+)", power).group(1))
        d["total_s"] = float(re.search(r"\| \*\*total\*\* \| \*\*([\d.]+)\*\*", stats).group(1))
        d["max_error_m"] = stat(stats, "max_error_m")
        d["splits"] = int(stat(stats, "points_inserted"))
        d["flips"] = int(stat(stats, "edge_flips"))
        runs.setdefault((c, v), []).append(d)
    for k in runs:
        runs[k].sort(key=lambda d: d["repeat"])
    return runs


def pct(new: float, old: float) -> str:
    return f"{100 * (new / old - 1):+.2f} %" if old else "-"


def table(header: list[str], rows: list[list[str]]) -> list[str]:
    out = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    return out + ["| " + " | ".join(r) + " |" for r in rows]


def hashes(ds: list[dict], key: str) -> set[str]:
    return {d[key] for d in ds}


def main() -> None:
    runs = load([HERE / "raw"])
    old = load([OLD / "raw", OLD / "raw1m"])
    timed = {k: [d for d in v if d["repeat"] > 0] for k, v in runs.items()}
    lines: list[str] = []

    lines += ["### Power, every run (catchments and tile: `pmset -g batt` before and after; 1 m benchmark: `run.json`)", ""]
    rows = []
    for (c, v), ds in sorted(runs.items()):
        for d in ds:
            states = sorted({("AC" if "AC Power" in ln else "battery") for ln in d["power_lines"] if "drawing" in ln})
            pcts = [re.search(r"(\d+)%; ([\w ]+);", ln) for ln in d["power_lines"] if "InternalBattery" in ln]
            rows.append([f"{c}-{v}-r{d['repeat']}", " / ".join(states),
                         " -> ".join(f"{p.group(1)} % {p.group(2)}" for p in pcts if p), f"{d['proc_s']:.1f}"])  # fmt: skip
    for p in sorted((HERE / "bench").glob("b1m-*/run.json")):
        pw = json.loads(p.read_text())["power"]
        pcts = re.findall(r"(\d+)%; ([\w ]+);", pw["raw"])
        rows.append([p.parent.name, pw["state"], " -> ".join(f"{a} % {b}" for a, b in pcts), "-"])
    lines += table(["run", "power", "battery before -> after", "process s"], rows) + [""]

    lines += ["### Byte-identity with the first acceptance (34b546c4, `../raw`, `../raw1m`)", ""]
    rows = []
    for c in CATCH:
        for v in VARIANTS:
            new, was = runs.get((c, v), []), old.get((c, v), [])
            a = hashes(new, "arrays_sha256") == hashes(was, "arrays_sha256") and len(hashes(new, "arrays_sha256")) == 1
            vt = hashes(new, "vtk_sha256") == hashes(was, "vtk_sha256") and len(hashes(new, "vtk_sha256")) == 1
            rows.append([CATCH[c], LABEL[v], f"{len(new)} runs vs {len(was)}", next(iter(hashes(new, "arrays_sha256")))[:12],
                         "equal" if a else "DIFFER", "equal" if vt else "DIFFER"])  # fmt: skip
    lines += table(["catchment", "build", "runs (now vs then)", "arrays sha256", "arrays", ".vtk from POINTS on"], rows) + [""]

    lines += ["### Mesh and quality (every repeat; r0 included)", ""]
    rows = []
    for c in CATCH:
        for v in VARIANTS:
            ds = runs[(c, v)]
            d = ds[0]
            rows.append([CATCH[c], LABEL[v], f"{d['triangles']:,}".replace(",", " "), str(d["under_1"]),
                         f"{100 * d['under_1'] / d['triangles']:.4f} %", f"{d['worst_angle']:.6g}°",
                         str(d["max_degree"]), f"{d['max_error_m']:.6f}",
                         f"{d['delaunay_violations']} of {d['delaunay_checked']:,}".replace(",", " "),
                         f"{len(ds)} runs, {len(hashes(ds, 'arrays_sha256'))} distinct"])  # fmt: skip
    lines += table(["catchment", "build", "triangles", "< 1°", "share < 1°", "worst", "max degree",
                    "max height error m", "Delaunay violations", "identical across runs"], rows) + [""]  # fmt: skip

    lines += ["### The 20c-1 gates (`docs/increments/20c-soft-quality.md`, PRs and gates)", ""]
    rows = []
    for c, g in GATES.items():
        b, h = runs[(c, "base")][0], runs[(c, "head")][0]
        share = 100 * h["under_1"] / h["triangles"]
        tri = 100 * (h["triangles"] / b["triangles"] - 1)
        rows.append([CATCH[c], "share under 1°", f"≤ {g['share']} %", f"{share:.4f} %", "pass" if share <= g["share"] else "MISS"])
        rows.append([CATCH[c], "triangles vs master", "≤ +1 %", f"{tri:+.3f} %", "pass" if tri <= 1.0 else "MISS"])
        ok = h["worst_angle"] >= b["worst_angle"] and h["worst_angle"] >= g["worst"]
        rows.append([CATCH[c], "worst angle", f"≥ master's {b['worst_angle']:.6g}°", f"{h['worst_angle']:.6g}°", "pass" if ok else "MISS"])
        nf, bnf = runs[(c, "nofeet")], old[(c, "basenofeet")]
        same = hashes(nf, "arrays_sha256") == hashes(bnf, "arrays_sha256") and hashes(nf, "vtk_sha256") == hashes(bnf, "vtk_sha256")
        rows.append([CATCH[c], "--no-constraint-feet bit-identical to master --no-constraint-feet (`../raw`)",
                     "arrays and .vtk equal", "equal" if same else "DIFFER", "pass" if same else "MISS"])  # fmt: skip
        det = len(hashes(runs[(c, "head")], "arrays_sha256")) == 1
        rows.append([CATCH[c], "determinism", "one mesh over every repeat", f"{len(runs[(c, 'head')])} runs", "pass" if det else "MISS"])
        tol = max(d["max_error_m"] for d in runs[(c, "head")])
        rows.append([CATCH[c], "largest height error", "≤ 10 m", f"{tol:.6f} m", "pass" if tol <= 10 else "MISS"])
    lines += table(["catchment", "gate", "threshold", "measured", "result"], rows) + [""]

    def med(c: str, v: str, p: str, src: dict = timed) -> list[float]:
        return [d["total_s"] if p == "total" else d["phases_s"].get(p, 0.0) for d in src.get((c, v), [])]

    n = sorted({len(v) for v in timed.values()})
    lines += [f"### Refine phases: median seconds over repeats r1 and on ({n} runs per build), threads 10 (hardware concurrency)", ""]
    rows = []
    for c in CATCH:
        for p in [*PHASES, "total"]:
            row = [CATCH[c], p]
            for v in VARIANTS:
                xs = med(c, v, p)
                row.append(f"{statistics.median(xs):.4f} ({min(xs):.4f} to {max(xs):.4f})")
            row += [pct(statistics.median(med(c, "head", p)), statistics.median(med(c, "nofeet", p))),
                    pct(statistics.median(med(c, "head", p)), statistics.median(med(c, "base", p)))]  # fmt: skip
            rows.append(row)
    lines += table(["catchment", "phase", *(f"{LABEL[v]}: median (min to max)" for v in VARIANTS),
                    "feet on vs off", "feet on vs master"], rows) + [""]  # fmt: skip

    lines += ["### The split phase per split (ruling 5's 2 % limit, on comparable work)", "",
              "Splits are `points_inserted` from each run's `--stats` (the points refinement's main loop added;",
              "the start-quality and final-check points are counted elsewhere). Seconds per split = median split",
              "phase seconds / splits (each build's count is the same in every repeat).", ""]  # fmt: skip
    rows = []
    for c in CATCH:
        s = {v: statistics.median(med(c, v, SPLIT)) for v in VARIANTS}
        k = {v: {d["splits"] for d in runs[(c, v)]} for v in VARIANTS}
        assert all(len(x) == 1 for x in k.values()), k
        k = {v: next(iter(x)) for v, x in k.items()}
        us = {v: 1e6 * s[v] / k[v] for v in VARIANTS}
        rows.append([CATCH[c], *(f"{k[v]:,}".replace(",", " ") for v in VARIANTS), *(f"{us[v]:.4f}" for v in VARIANTS),
                     pct(s["head"], s["nofeet"]), pct(us["head"], us["nofeet"]), pct(us["head"], us["base"]),
                     "within" if us["head"] / us["nofeet"] - 1 <= 0.02 else "OVER"])  # fmt: skip
    lines += table(["catchment", *(f"splits, {v}" for v in VARIANTS), *(f"µs per split, {v}" for v in VARIANTS),
                    "seconds, on vs off", "per split, on vs off", "per split, on vs master", "2 % (per split)"], rows) + [""]  # fmt: skip

    lines += ["### Master's own spread (base runs, split phase: (max - min) / median)", ""]
    rows = [[CATCH[c], f"{100 * (max(xs) - min(xs)) / statistics.median(xs):.1f} %"] for c in CATCH for xs in [med(c, "base", SPLIT)]]
    lines += table(["catchment", "spread"], rows) + [""]

    lines += ["### For reference only: the first acceptance's split-phase medians (34b546c4, another hour; `../raw`, `../raw1m`)", ""]
    otimed = {k: [d for d in v if d["repeat"] > 0] for k, v in old.items()}
    rows = [[CATCH[c], *(f"{statistics.median(med(c, v, SPLIT, otimed)):.4f}" for v in VARIANTS)] for c in CATCH]
    lines += table(["catchment", "master then", "20c-1 34b546c4", "34b546c4 feet off"], rows) + [""]

    lines += ["### The 1 m benchmark and thread sweep (`tools/bench.py run`, `bench/b1m-*`; `bench_summarize.py bench b1m`)", ""]
    done = subprocess.run([sys.executable, str(HERE / "bench_summarize.py"), str(HERE / "bench"), "b1m"],
                          capture_output=True, text=True, check=True)  # fmt: skip
    lines += done.stdout.splitlines()
    block = "\n".join(lines)
    readme = HERE / "README.md"
    if readme.exists():
        text = readme.read_text()
        a, b = text.index(BEGIN), text.index(END)
        readme.write_text(text[: a + len(BEGIN)] + "\n\n" + block + "\n" + text[b:])
    print(block)


if __name__ == "__main__":
    main()
