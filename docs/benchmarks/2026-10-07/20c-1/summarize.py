"""Tables for 20c-1's acceptance, from raw/ only (@perf, 2026-10-07).

``python3 summarize.py`` rewrites the block between the two marker lines in
README.md (and prints it). Runs: raw/<catchment>-<variant>-r<k>.{json,power}
and raw/<...>_stats.md, as run.sh writes them; raw1m/ likewise from onem.sh (the 1 m
tile, no warm-up repeat; its process seconds are not recorded, shown as 0). r0 is a warm-up: its mesh is in
the quality and identity tables, its times are not in the timing tables.
"""

import json
import re
import statistics
from pathlib import Path

HERE = Path(__file__).resolve().parent
RAW = HERE / "raw"
CATCH = {"lagan": "Lagan", "numed": "Numedalslagen", "tile": "1 m tile (tolerance 1)"}
VARIANTS = ["base", "head", "nofeet", "basenofeet"]
LABEL = {
    "base": "master ed125121",
    "head": "20c-1 34b546c4",
    "nofeet": "20c-1, --no-constraint-feet",
    "basenofeet": "master, --no-constraint-feet",
}
# The 20c-1 row of "PRs and gates" in docs/increments/20c-soft-quality.md.
GATES = {"lagan": dict(share=0.09, worst=0.000412), "numed": dict(share=0.04, worst=0.000399)}
PHASES = [
    "refine",
    "refine: start quality",
    "refine: scan (parallel)",
    "refine: split + flip (serial)",
    "final check: scan (parallel)",
    "final check: split + flip (serial)",
]
BEGIN, END = "<!-- tables: generated by summarize.py -->", "<!-- end of generated tables -->"


def load() -> dict[tuple[str, str], list[dict]]:
    runs: dict[tuple[str, str], list[dict]] = {}
    for f in sorted([*RAW.glob("*-r*.json"), *(HERE / "raw1m").glob("*-r*.json")]):
        m = re.fullmatch(r"(\w+)-(\w+)-r(\d+)\.json", f.name)
        if not m:
            continue
        c, v, r = m.group(1), m.group(2), int(m.group(3))
        d = json.loads(f.read_text())
        power = (f.parent / f"{c}-{v}-r{r}.power").read_text()
        stats = (f.parent / f"{c}-{v}-r{r}_stats.md").read_text()
        d["repeat"] = r
        d["power_lines"] = [ln for ln in power.splitlines() if "InternalBattery" in ln or "drawing" in ln]
        d["proc_s"] = float(re.search(r"proc_s: (\S+)", power).group(1))
        d["total_s"] = float(re.search(r"\| \*\*total\*\* \| \*\*([\d.]+)\*\*", stats).group(1))
        d["max_error_m"] = float(re.search(r"\| ([\d.e+-]+) \| `max_error_m`", stats).group(1))
        runs.setdefault((c, v), []).append(d)
    for k in runs:
        runs[k].sort(key=lambda d: d["repeat"])
    return runs


def pct(new: float, old: float) -> str:
    if not old:
        return "- (no such phase)"
    return f"{100 * (new / old - 1):+.2f} %"


def table(header: list[str], rows: list[list[str]]) -> list[str]:
    out = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    return out + ["| " + " | ".join(r) + " |" for r in rows]


def main() -> None:
    runs = load()
    lines: list[str] = []
    timed = {k: [d for d in v if d["repeat"] > 0] for k, v in runs.items()}

    lines += ["### Power, every run", ""]
    rows = []
    for (c, v), ds in sorted(runs.items()):
        for d in ds:
            states = sorted({("AC" if "AC Power" in ln else "battery") for ln in d["power_lines"] if "drawing" in ln})
            pcts = [re.search(r"(\d+)%; ([\w ]+);", ln) for ln in d["power_lines"] if "InternalBattery" in ln]
            rows.append([f"{c}-{v}-r{d['repeat']}", " / ".join(states),
                         " -> ".join(f"{p.group(1)} % {p.group(2)}" for p in pcts if p), f"{d['proc_s']:.1f}"])  # fmt: skip
    lines += table(["run", "power before and after", "battery before -> after", "process s"], rows) + [""]

    lines += ["### Mesh and quality (every repeat; r0 included)", ""]
    rows = []
    for c in CATCH:
        for v in VARIANTS:
            ds = runs.get((c, v), [])
            if not ds:
                continue
            d = ds[0]
            hashes = {x["arrays_sha256"] for x in ds}
            rows.append([CATCH[c], LABEL[v], f"{d['triangles']:,}".replace(",", " "), str(d["under_1"]),
                         f"{100 * d['under_1'] / d['triangles']:.4f} %", str(d["under_10"]), f"{d['worst_angle']:.6g}°",
                         f"{d['angle_median']:.2f}°", str(d["max_degree"]), f"{d['max_error_m']:.6f}",
                         f"{d['delaunay_violations']} of {d['delaunay_checked']:,} ({d['delaunay_ambiguous']} near-tie, exact)".replace(",", " "),
                         f"{len(ds)} runs, {len(hashes)} distinct", d["arrays_sha256"][:12]])  # fmt: skip
    lines += table(["catchment", "build", "triangles", "< 1°", "share < 1°", "< 10°", "worst", "median",
                    "max degree", "max height error m", "Delaunay violations", "identical across runs",
                    "mesh sha256 (arrays)"], rows) + [""]  # fmt: skip

    lines += ["### The 20c-1 gates (`docs/increments/20c-soft-quality.md`, PRs and gates)", ""]
    rows = []
    for c, g in GATES.items():
        b, h = runs[(c, "base")][0], runs[(c, "head")][0]
        share = 100 * h["under_1"] / h["triangles"]
        tri = 100 * (h["triangles"] / b["triangles"] - 1)
        rows.append([CATCH[c], "share under 1°", f"≤ {g['share']} %", f"{share:.4f} %", "pass" if share <= g["share"] else "MISS"])
        rows.append([CATCH[c], "triangles vs master", "≤ +1 %", f"{tri:+.3f} %", "pass" if tri <= 1.0 else "MISS"])
        rows.append([CATCH[c], "worst angle", f"≥ master's {b['worst_angle']:.6g}° (design: {g['worst']}°)",
                     f"{h['worst_angle']:.6g}°", "pass" if h["worst_angle"] >= b["worst_angle"] and h["worst_angle"] >= g["worst"] else "MISS"])  # fmt: skip
        nf, bnf = runs[(c, "nofeet")], runs[(c, "basenofeet")]
        same = {d["arrays_sha256"] for d in nf} == {d["arrays_sha256"] for d in bnf} and len({d["arrays_sha256"] for d in nf}) == 1
        vtk = {d["vtk_sha256"] for d in nf} == {d["vtk_sha256"] for d in bnf}
        rows.append([CATCH[c], "--no-constraint-feet bit-identical to master --no-constraint-feet",
                     "arrays and .vtk from POINTS on equal", f"arrays {'equal' if same else 'DIFFER'}, .vtk {'equal' if vtk else 'DIFFER'}",
                     "pass" if same and vtk else "MISS"])  # fmt: skip
        dflt = {d["arrays_sha256"] for d in nf} == {d["arrays_sha256"] for d in runs[(c, "base")]}
        rows.append([CATCH[c], "(not a gate) --no-constraint-feet vs master's default", "-", "equal" if dflt else "differ", "-"])
        det = len({d["arrays_sha256"] for d in runs[(c, "head")]}) == 1
        rows.append([CATCH[c], "determinism, 20c-1 default", "one mesh over every repeat",
                     f"{len(runs[(c, 'head')])} runs, {len({d['arrays_sha256'] for d in runs[(c, 'head')]})} distinct", "pass" if det else "MISS"])  # fmt: skip
        tol = all(d["max_error_m"] <= 10 for d in runs[(c, "head")])
        rows.append([CATCH[c], "largest height error (the CLI's own check)", "≤ 10 m",
                     f"{max(d['max_error_m'] for d in runs[(c, 'head')]):.6f} m", "pass" if tol else "MISS"])  # fmt: skip
    lines += table(["catchment", "gate", "threshold", "measured", "result"], rows) + [""]

    n = {k: len(v) for k, v in timed.items()}
    lines += [f"### Timings: median seconds over repeats r1 and on (runs per build: {sorted(set(n.values()))}), threads 10 (hardware concurrency)", ""]  # fmt: skip
    rows = []
    for c in CATCH:
        for p in [*PHASES, "total"]:
            row = [CATCH[c], p]
            for v in VARIANTS:
                xs = [d["total_s"] if p == "total" else d["phases_s"].get(p, 0.0) for d in timed.get((c, v), [])]
                row.append(f"{statistics.median(xs):.4f} ({min(xs):.4f} to {max(xs):.4f})" if xs else "-")
            rows.append(row)
    lines += table(["catchment", "phase", *(f"{LABEL[v]}: median (min to max)" for v in VARIANTS)], rows) + [""]

    lines += ["### Feet on against feet off, and against master (change of the medians)", ""]
    rows = []
    for c in CATCH:
        for p in [*PHASES, "total"]:
            med = {}
            for v in VARIANTS:
                xs = [d["total_s"] if p == "total" else d["phases_s"].get(p, 0.0) for d in timed.get((c, v), [])]
                med[v] = statistics.median(xs) if xs else None
            rows.append([CATCH[c], p, pct(med["head"], med["nofeet"]), pct(med["head"], med["base"]),
                         pct(med["nofeet"], med["basenofeet"])])  # fmt: skip
    lines += table(["catchment", "phase", "20c-1 vs 20c-1 feet off", "20c-1 vs master",
                    "20c-1 feet off vs master feet off"], rows) + [""]  # fmt: skip
    lines += ["### The 1 m benchmark and thread sweep (`tools/bench.py run`, `bench/b1m-*`; `bench_summarize.py bench b1m`)", ""]
    import subprocess, sys  # noqa: E401

    done = subprocess.run([sys.executable, str(HERE / "bench_summarize.py"), str(HERE / "bench"), "b1m"],
                          capture_output=True, text=True, check=True)  # fmt: skip
    lines += done.stdout.splitlines()
    block = "\n".join(lines)
    readme = HERE / "README.md"
    if readme.exists():
        text = readme.read_text()
        a, b = text.index(BEGIN), text.index(END)
        readme.write_text(text[: a + len(BEGIN)] + "\n\n" + block + "\n" + text[b:])
    print(block)


if __name__ == "__main__":
    main()
