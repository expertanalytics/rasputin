"""Tables for 20c-2's acceptance, from raw files only (@perf, 2026-10-07).

``python3 summarize.py`` rewrites the block between the two marker lines in
README.md (and prints it). It reads raw/<catchment>-<variant>-r<k>.{json,power,log}
and raw/<...>_stats.md as run.sh writes them, bench/b1m-*/run.json from
pairs.sh, and, for the cross-check rows only, 20c-1's re-time
../20c-1/fix-69f37d1c/raw/. r0 is a warm-up: its mesh is in the mesh tables,
its times are not in the timing tables. Adapted from ../20c-1/fix-69f37d1c/summarize.py.
Every gate compares the raw values; nothing is rounded before it is judged.
"""

import json
import re
import statistics
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
OLD = HERE.parent / "20c-1" / "fix-69f37d1c" / "raw"
CATCH = {"tile": "1 m tile (tolerance 1)", "lagan": "Lagan", "numed": "Numedalslagen"}
VARIANTS = ["pre", "base", "head", "headm1", "nofeet"]
TIMED = ["base", "head", "headm1", "nofeet"]
LABEL = {
    "pre": "master 2764ef71 (before 20c-1)", "base": "master 41bda81a (20c-1)",
    "head": "20c-2 600b2acb, gain 0 (default)", "headm1": "20c-2 600b2acb, --start-quality-gain -1",
    "nofeet": "20c-2 600b2acb, --no-constraint-feet",
}  # fmt: skip
PHASES = ["refine", "refine: start quality", "refine: scan (parallel)", "refine: split + flip (serial)"]
SPLIT, START = "refine: split + flip (serial)", "refine: start quality"
COUNTS = ["start_quality_points_inserted", "start_quality_points_skipped", "start_quality_points_without_gain",
          "start_quality_points_snapped_to_lines", "start_quality_lines_split", "points_inserted"]  # fmt: skip
BEGIN, END = "<!-- tables: generated by summarize.py -->", "<!-- end of generated tables -->"


def stat(stats: str, name: str) -> float | None:
    m = re.search(r"\| ([\d.e+-]+) \| `" + name + "`", stats)
    return float(m.group(1)) if m else None


def load(d: Path) -> dict[tuple[str, str], list[dict]]:
    runs: dict[tuple[str, str], list[dict]] = {}
    for f in sorted(d.glob("*-r*.json")):
        m = re.fullmatch(r"(\w+)-(\w+)-r(\d+)\.json", f.name)
        if not m:
            continue
        c, v, r = m.group(1), m.group(2), int(m.group(3))
        x = json.loads(f.read_text())
        power = (d / f"{c}-{v}-r{r}.power").read_text()
        stats = (d / f"{c}-{v}-r{r}_stats.md").read_text()
        x["repeat"] = r
        x["power_lines"] = [ln for ln in power.splitlines() if "InternalBattery" in ln or "drawing" in ln]
        x["proc_s"] = float(re.search(r"proc_s: (\S+)", power).group(1))
        x["total_s"] = float(re.search(r"\| \*\*total\*\* \| \*\*([\d.]+)\*\*", stats).group(1))
        x["max_error_m"] = stat(stats, "max_error_m")
        x["counts"] = {k: stat(stats, k) for k in COUNTS}
        log = d / f"{c}-{v}-r{r}.log"
        x["loaded"] = log.read_text().splitlines()[:2] if log.exists() else []
        runs.setdefault((c, v), []).append(x)
    for k in runs:
        runs[k].sort(key=lambda x: x["repeat"])
    return runs


def pct(new: float, old: float) -> str:
    return f"{100 * (new / old - 1):+.2f} %" if old else "-"


def table(header: list[str], rows: list[list[str]]) -> list[str]:
    out = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    return out + ["| " + " | ".join(r) + " |" for r in rows]


def hashes(ds: list[dict], key: str) -> set[str]:
    return {d[key] for d in ds}


def same(a: list[dict], b: list[dict]) -> bool:
    return all(len(hashes(a + b, k)) == 1 for k in ("arrays_sha256", "vtk_sha256")) and bool(a) and bool(b)


def n(x: float | None) -> str:
    return "-" if x is None else f"{int(x):,}".replace(",", " ")


def main() -> None:
    runs = load(HERE / "raw")
    old = load(OLD) if OLD.exists() else {}
    timed = {k: [d for d in v if d["repeat"] > 0] for k, v in runs.items()}
    present = [(c, v) for c in CATCH for v in VARIANTS if (c, v) in runs]
    lines: list[str] = []

    lines += ["### The 20c-2 gates (`docs/increments/20c-soft-quality.md`, PRs and gates)", "",
              "master = 2764ef71 (the merge before 20c-1); 20c-1 = master 41bda81a; 20c-2 = gain 0, the CLI default.", ""]  # fmt: skip
    rows = []
    for c in ("lagan", "numed"):
        if not all((c, v) in runs for v in ("pre", "base", "head", "headm1")):
            continue
        p, b, h = runs[(c, "pre")][0], runs[(c, "base")][0], runs[(c, "head")][0]
        r = h["triangles"] / p["triangles"]
        rows.append([CATCH[c], "triangles ≤ 0.95 × master's", f"≤ {0.95 * p['triangles']:.2f} ({n(p['triangles'])} × 0.95)",
                     f"{n(h['triangles'])} ({r:.4f} ×)", "pass" if h["triangles"] <= 0.95 * p["triangles"] else "MISS"])  # fmt: skip
        r = h["under_1"] / b["under_1"]
        rows.append([CATCH[c], "slivers under 1° ≤ 0.75 × 20c-1's", f"≤ {0.75 * b['under_1']:.2f} ({b['under_1']} × 0.75)",
                     f"{h['under_1']} ({r:.4f} ×)", "pass" if h["under_1"] <= 0.75 * b["under_1"] else "MISS"])  # fmt: skip
        r = h["worst_angle"] / b["worst_angle"]
        rows.append([CATCH[c], "worst angle ≥ 0.95 × 20c-1's", f"≥ {0.95 * b['worst_angle']:.9g}° ({b['worst_angle']:.9g}° × 0.95)",
                     f"{h['worst_angle']:.9g}° ({r:.6f} ×)", "pass" if h["worst_angle"] >= 0.95 * b["worst_angle"] else "MISS"])  # fmt: skip
        ok = same(runs[(c, "headm1")], runs[(c, "base")])
        rows.append([CATCH[c], "--start-quality-gain -1 bit-identical to 20c-1", "arrays and .vtk from POINTS on equal, every repeat",
                     f"{len(runs[(c, 'headm1')])} vs {len(runs[(c, 'base')])} runs, " + ("equal" if ok else "DIFFER"), "pass" if ok else "MISS"])  # fmt: skip
        det = len(hashes(runs[(c, "head")], "arrays_sha256")) == 1 and len(hashes(runs[(c, "head")], "vtk_sha256")) == 1
        rows.append([CATCH[c], "determinism (gain 0)", "one mesh over every repeat", f"{len(runs[(c, 'head')])} runs, "
                     f"{len(hashes(runs[(c, 'head')], 'arrays_sha256'))} distinct", "pass" if det else "MISS"])  # fmt: skip
        tol = max(d["max_error_m"] for d in runs[(c, "head")])
        rows.append([CATCH[c], "largest height error (gain 0)", "≤ 10 m", f"{tol:.9f} m", "pass" if tol <= 10 else "MISS"])
        dv = max(d["delaunay_violations"] for d in runs[(c, "head")])
        rows.append([CATCH[c], "constrained Delaunay (gain 0)", "0 violations", f"{dv} of {n(h['delaunay_checked'])} checked", "pass" if dv == 0 else "MISS"])  # fmt: skip
    lines += table(["catchment", "gate", "threshold", "measured", "result"], rows) + [""]

    lines += ["### Mesh and quality, exact from the output arrays (every repeat; r0 included)", ""]
    rows = []
    for c, v in present:
        ds = runs[(c, v)]
        d = ds[0]
        rows.append([CATCH[c], LABEL[v], n(d["triangles"]), str(d["under_1"]), f"{100 * d['under_1'] / d['triangles']:.4f} %",
                     f"{d['worst_angle']:.9g}°", str(d["max_degree"]), f"{d['max_error_m']:.6f}",
                     f"{d['delaunay_violations']} of {n(d['delaunay_checked'])}",
                     f"{len(ds)} runs, {len(hashes(ds, 'arrays_sha256'))} distinct", d["arrays_sha256"][:12]])  # fmt: skip
    lines += table(["catchment", "build", "triangles", "< 1°", "share < 1°", "worst", "max degree",
                    "max height error m", "Delaunay violations", "identical across runs", "arrays sha256"], rows) + [""]  # fmt: skip

    lines += ["### Quality-start and refinement counts (`--stats`; the same in every repeat, else listed)", ""]
    rows = []
    for c, v in present:
        cells = []
        for k in COUNTS:
            vals = sorted({d["counts"][k] for d in runs[(c, v)]}, key=lambda x: -1 if x is None else x)
            cells.append(" / ".join(n(x) for x in vals))
        rows.append([CATCH[c], LABEL[v], *cells])
    lines += table(["catchment", "build", "start: points added", "start: tries skipped (all reasons)",
                    "start: of them, without gain (R7)", "start: points snapped to lines (feet)",
                    "start: lines split (R8)", "refinement: points added"], rows) + [""]  # fmt: skip

    lines += ["### Cross-check with 20c-1's re-time (`../20c-1/fix-69f37d1c/raw`, another session)", ""]
    rows = []
    for c in CATCH:
        for v, ov, what in (("base", "head", "20c-1 69f37d1c"), ("pre", "base", "master ed125121")):
            if (c, v) in runs and (c, ov) in old:
                rows.append([CATCH[c], f"{LABEL[v]} vs {what}", "equal" if same(runs[(c, v)], old[(c, ov)]) else "DIFFER"])
    lines += table(["catchment", "meshes compared (arrays and .vtk)", "result"], rows) + [""]

    def xs(c: str, v: str, p: str) -> list[float]:
        return [d["total_s"] if p == "total" else d["phases_s"].get(p, 0.0) for d in timed.get((c, v), [])]

    def med(c: str, v: str, p: str) -> float:
        return statistics.median(xs(c, v, p))

    counts = sorted({len(timed[(c, v)]) for c in CATCH for v in TIMED if (c, v) in timed})
    lines += [f"### Phases: median seconds over repeats r1 and on ({counts} runs per build), threads 10 (the CLI default)", ""]
    rows = []
    for c in CATCH:
        if not all(timed.get((c, v)) for v in TIMED):
            continue
        for p in [*PHASES, "total"]:
            row = [CATCH[c], p, *(f"{med(c, v, p):.4f} ({min(xs(c, v, p)):.4f} to {max(xs(c, v, p)):.4f})" for v in TIMED)]
            row += [pct(med(c, "head", p), med(c, "headm1", p)), pct(med(c, "head", p), med(c, "base", p)),
                    pct(med(c, "headm1", p), med(c, "base", p)), pct(med(c, "head", p), med(c, "nofeet", p))]  # fmt: skip
            rows.append(row)
    lines += table(["catchment", "phase", *(f"{LABEL[v]}: median (min to max)" for v in TIMED),
                    "gain 0 vs -1", "gain 0 vs 20c-1", "gain -1 vs 20c-1", "gain 0 vs feet off"], rows) + [""]  # fmt: skip

    lines += ["### The split-phase limit (`docs/increments/20c-soft-quality.md`, \"The split-phase limit, judged after the fix\")", ""]
    rows = []
    if all(timed.get(("tile", v)) for v in TIMED):
        t = {v: med("tile", v, SPLIT) for v in TIMED}
        identical = same(runs[("tile", "head")], runs[("tile", "nofeet")]) and same(runs[("tile", "head")], runs[("tile", "base")])
        for v in ("nofeet", "base"):
            ch = t["head"] / t[v] - 1
            rows.append(["1. tile, no cost where no foot is placed", f"split phase, gain 0 vs {LABEL[v]}", "≤ +2 %",
                         f"{100 * ch:+.2f} % (meshes identical: {identical})", "met" if ch <= 0.02 else "NOT MET"])  # fmt: skip
    for c in ("lagan", "numed"):
        if not all(timed.get((c, v)) for v in TIMED):
            continue
        for p in (SPLIT, "total"):
            ch = med(c, "head", p) / med(c, "base", p) - 1
            ok = ch <= 0.02 if p == SPLIT else abs(ch) <= 0.02
            rows.append([f"2. {CATCH[c]}, no slower than what Ola runs today", f"{p}, gain 0 vs 20c-1",
                         "≤ +2 %" if p == SPLIT else "within 2 %", f"{100 * ch:+.2f} %", "met" if ok else "NOT MET"])  # fmt: skip
        for p in (START, "refine"):
            rows.append([f"3. {CATCH[c]}, reported, not gated", f"{p}, gain 0 vs 20c-1 / vs feet off", "-",
                         f"{pct(med(c, 'head', p), med(c, 'base', p))} / {pct(med(c, 'head', p), med(c, 'nofeet', p))}", "-"])  # fmt: skip
    lines += table(["point", "measure", "limit", "measured (medians)", "result"], rows) + [""]

    lines += ["### The split phase per split (for reading point 2: the meshes differ, so the work differs)", "",
              "Splits are `points_inserted` from `--stats` (refinement's main loop). µs per split = median split-phase",
              "seconds / splits. Reported beside the limit, which is written in seconds; not a gate.", ""]  # fmt: skip
    rows = []
    for c in CATCH:
        if not all(timed.get((c, v)) for v in TIMED):
            continue
        k = {v: {d["counts"]["points_inserted"] for d in runs[(c, v)]} for v in TIMED}
        assert all(len(x) == 1 for x in k.values()), k
        k1 = {v: next(iter(x)) for v, x in k.items()}
        us = {v: 1e6 * med(c, v, SPLIT) / k1[v] for v in TIMED}
        rows.append([CATCH[c], *(n(k1[v]) for v in TIMED), *(f"{us[v]:.4f}" for v in TIMED),
                     pct(k1["head"], k1["base"]), pct(us["head"], us["base"]), pct(us["head"], us["nofeet"])])  # fmt: skip
    lines += table(["catchment", *(f"splits, {v}" for v in TIMED), *(f"µs per split, {v}" for v in TIMED),
                    "splits, gain 0 vs 20c-1", "per split, gain 0 vs 20c-1", "per split, gain 0 vs feet off"], rows) + [""]  # fmt: skip

    tile = load(HERE / "raw-tile") if (HERE / "raw-tile").exists() else {}
    if tile.get(("tile", "base")) and tile.get(("tile", "head")):
        tt = {v: [d for d in tile[("tile", v)] if d["repeat"] > 0] for v in ("base", "head")}
        lines += [f"### A longer tile series for point 1 (`run.sh tile 0 .. 20`, `raw-tile/`; r0 a warm-up; {len(tt['base'])} and "
                  f"{len(tt['head'])} timed runs, base and head alternating)", ""]  # fmt: skip
        rows = []
        for p in (*PHASES, "total"):
            v = {s: [d["total_s"] if p == "total" else d["phases_s"].get(p, 0.0) for d in tt[s]] for s in tt}
            rows.append([p, *(f"{statistics.median(v[s]):.4f} ({min(v[s]):.4f} to {max(v[s]):.4f})" for s in ("base", "head")),
                         pct(statistics.median(v["head"]), statistics.median(v["base"]))])  # fmt: skip
        ident = same(tile[("tile", "base")], tile[("tile", "head")]) and same(tile[("tile", "head")], runs.get(("tile", "base"), []))
        lines += table(["phase", f"{LABEL['base']}: median (min to max)", f"{LABEL['head']}: median (min to max)", "gain 0 vs 20c-1"], rows)
        lines += ["", f"Every mesh in the series equal to each other and to `raw/`'s tile meshes: {ident}.", ""]

    lines += ["### Spread of 20c-1's own runs (base, (max - min) / median)", ""]
    rows = [[CATCH[c], *(f"{100 * (max(xs(c, 'base', p)) - min(xs(c, 'base', p))) / med(c, 'base', p):.1f} %" for p in (START, SPLIT, "refine", "total"))]
            for c in CATCH if timed.get((c, "base"))]  # fmt: skip
    lines += table(["catchment", START, SPLIT, "refine", "total"], rows) + [""]

    lines += ["### Power, every run (`pmset -g batt` before and after; 1 m benchmark: `run.json`)", ""]
    rows = []
    for (c, v), ds in sorted(runs.items()):
        for d in ds:
            states = sorted({("AC" if "AC Power" in ln else "battery") for ln in d["power_lines"] if "drawing" in ln})
            pcts = [re.search(r"(\d+)%; ([\w ]+);", ln) for ln in d["power_lines"] if "InternalBattery" in ln]
            rows.append([f"{c}-{v}-r{d['repeat']}", " / ".join(states),
                         " -> ".join(f"{p.group(1)} % {p.group(2)}" for p in pcts if p), f"{d['proc_s']:.1f}"])  # fmt: skip
    for p in sorted((HERE / "bench").glob("b1m-*/run.json")):
        pw = json.loads(p.read_text())["power"]
        pcts = re.findall(r"(\d+)%; ([\w ]+);", pw["raw"])
        rows.append([p.parent.name, pw["state"], " -> ".join(f"{a} % {b}" for a, b in pcts), "-"])
    lines += table(["run", "power", "battery before -> after", "process s"], rows) + [""]

    lines += ["### Where each run loaded tin_engine and _core from (first two lines of every `raw/*.log`)", ""]
    rows = []
    for (c, v), ds in sorted(runs.items()):
        seen = {tuple(ln.split(" = ", 1)[1] for ln in d["loaded"]) for d in ds}
        for te, core in sorted(seen):
            rows.append([f"{c}-{v}", f"{len(ds)}", f"`{te}`", f"`{core}`"])
    lines += table(["runs", "count", "tin_engine.__file__", "_core.__file__"], rows) + [""]

    if sorted((HERE / "bench").glob("b1m-*/run.json")):
        lines += ["### The 1 m benchmark and thread sweep (`tools/bench.py run`, `bench/b1m-*`; `bench_summarize.py bench b1m`)", "",
                  "base = master 41bda81a, head = 20c-2 600b2acb.", ""]  # fmt: skip
        done = subprocess.run([sys.executable, str(HERE / "bench_summarize.py"), str(HERE / "bench"), "b1m"],
                              capture_output=True, text=True, check=True)  # fmt: skip
        lines += done.stdout.splitlines()
    block = "\n".join(lines)
    readme = HERE / "README.md"
    if readme.exists():
        text = readme.read_text()
        a, b = text.index(BEGIN), text.index(END)
        readme.write_text(text[: a + len(BEGIN)] + "\n\n" + block + "\n" + text[b:])
    print(block)


if __name__ == "__main__":
    main()
